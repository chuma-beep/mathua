	reg.Register("numa.roots.muller", &mullerGen{})
	reg.Register("numa.interp.barycentric", &barycentricGen{})
	reg.Register("numa.interp.runge", &rungeGen{})
	reg.Register("numa.interp.piecewise_linear", &piecewiseLinearGen{})
