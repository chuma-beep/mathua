type w7TopologyRemainingGen struct{ kind string }

func (g *w7TopologyRemainingGen) Generate(ctx generator.GeneratorContext) generator.Problem {
	kp := ctx.KPOrdinal
	if kp < 1 || kp > 3 {
		kp = 1 + rand.Intn(3)
	}
	switch g.kind {
	case "filters":
		return w7Filters(kp)
	case "paracompact":
		return w7Paracompact(kp)
	case "partition_unity":
		return w7PartitionUnity(kp)
	case "function_space":
		return w7FunctionSpace(kp)
	case "uniform_space":
		return w7UniformSpace(kp)
	case "limit_point_compact":
		return w7LimitPointCompact(kp)
	case "continuum":
		return w7Continuum(kp)
	case "homotopy_group":
		return w7HomotopyGroup(kp)
	case "fibration":
		return w7Fibration(kp)
	case "cofibration":
		return w7Cofibration(kp)
	case "simplicial_homology":
		return w7SimplicialHomology(kp)
	case "singular_homology":
		return w7SingularHomology(kp)
	case "poincare_duality":
		return w7PoincareDuality(kp)
	case "jones_polynomial":
		return w7JonesPolynomial(kp)
	case "seifert_surface":
		return w7SeifertSurface(kp)
	case "brouwer":
		return w7Brouwer(kp)
	}
	return generator.Problem{Question: "What is 2 + 2? (enter a number)", Answer: "4", Explanation: "2 + 2 = 4."}
}

func w7Filters(kp int) generator.Problem {
	n := w7TR(3, 12)
	s := w7TR(1, n)
	f := map[string]string{"n": strconv.Itoa(n), "s": strconv.Itoa(s)}
	switch kp {
	case 1:
		size := 1 << (n - s)
		return w7T(kp, fmt.Sprintf("On a %d-element set, the principal filter generated by a subset of size %d contains how many supersets?", n, s), strconv.Itoa(size),
			fmt.Sprintf("There are \\(2^{%d-%d}=%d\\) supersets.", n, s, size), f)
	case 2:
		return w7T(kp, fmt.Sprintf("How many ultrafilters does a finite %d-element set with a principal filter generated by a set of size %d have?", n, s), strconv.Itoa(n),
			"Every ultrafilter on a finite set is principal, and there is one for each element.", f)
	default:
		return w7T(kp, fmt.Sprintf("Does the principal filter generated by a subset of size %d on a %d-element set converge to that subset in the finite topology? Enter 1 for yes and 0 for no.", s, n), "1",
			"The principal filter contains every neighbourhood of the subset, so it converges to it.", f)
	}
}

