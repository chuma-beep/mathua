func w7LimitPointCompact(kp int) generator.Problem {
	k := w7TR(1, 12)
	closed := rand.Intn(2) == 0
	f := map[string]string{"k": strconv.Itoa(k), "closed": strconv.FormatBool(closed)}
	switch kp {
	case 1:
		return w7T(kp, fmt.Sprintf("A finite set has %d distinct points. How many limit points does it have in R?", k), "0",
			"A finite set in R has no limit points.", f)
	case 2:
		lo := w7TR(0, 3)
		hi := lo + w7TR(1, 4)
		left, right := "(", ")"
		ans := 0
		if closed {
			left, right = "[", "]"
			ans = 1
		}
		f["lo"] = strconv.Itoa(lo)
		f["hi"] = strconv.Itoa(hi)
		return w7T(kp, fmt.Sprintf("Is the interval \\(%s%d,%d%s\\) compact? Enter 1 for yes and 0 for no.", left, lo, hi, right), strconv.Itoa(ans),
			"Closed bounded intervals are compact; open intervals are not.", f)
	default:
		return w7T(kp, fmt.Sprintf("In a metric space with %d points, is limit-point compactness equivalent to compactness? Enter 1 for yes and 0 for no.", k), "1",
			"For metric spaces, limit-point compactness is equivalent to compactness.", f)
	}
}

