package graphtheory

import "github.com/chuma-beep/mathua/internal/generator"

// Register adds the graph-theory generators to reg.
func Register(reg *generator.Registry) {
	reg.Register("graph.isomorphism", &isomorphismGen{})
	reg.Register("graph.complement", &complementGen{})
	reg.Register("graph.subgraph", &subgraphGen{})
	reg.Register("graph.homomorphism", &homomorphismGen{})
	reg.Register("graph.product", &productGen{})
	reg.Register("graph.distance", &distanceGen{})
	reg.Register("graph.cut_vertex", &cutVertexGen{})
	reg.Register("graph.bridge", &bridgeGen{})
	reg.Register("graph.connectivity", &connectivityGen{})
	reg.Register("graph.menger", &mengerGen{})
	reg.Register("graph.matching", &matchingGen{})
	reg.Register("graph.perfect_matching", &perfectMatchingGen{})
	reg.Register("graph.tutte", &tutteGen{})
	reg.Register("graph.vertex_cover", &vertexCoverGen{})
	reg.Register("graph.independent_set", &independentSetGen{})
	reg.Register("graph.chromatic_polynomial", &chromaticPolynomialGen{})
	reg.Register("graph.brooks", &brooksGen{})
	reg.Register("graph.edge_coloring", &edgeColoringGen{})
	reg.Register("graph.perfect_graph", &perfectGraphGen{})
	reg.Register("graph.list_coloring", &listColoringGen{})
	reg.Register("graph.kuratowski", &kuratowskiGen{})
	reg.Register("graph.minor", &minorGen{})
	reg.Register("graph.treewidth", &treewidthGen{})
	reg.Register("graph.genus", &genusGen{})
	reg.Register("graph.outerplanar", &outerplanarGen{})
	reg.Register("graph.adjacency", &adjacencyGen{})
	reg.Register("graph.laplacian", &laplacianGen{})
	reg.Register("graph.matrix_tree", &matrixTreeGen{})
	reg.Register("graph.spectral_radius", &spectralRadiusGen{})
	reg.Register("graph.spectral_gap", &spectralGapGen{})
	reg.Register("graph.mantel", &mantelGen{})
	reg.Register("graph.turan", &turanGen{})
	reg.Register("graph.ramsey", &ramseyGen{})
	reg.Register("graph.random_threshold", &randomThresholdGen{})
	reg.Register("graph.moore_bound", &mooreBoundGen{})
	reg.Register("graph.max_flow", &maxFlowGen{})
	reg.Register("graph.tournament", &tournamentGen{})
	reg.Register("graph.strong_connectivity", &strongConnectivityGen{})
	reg.Register("graph.topological_sort", &topologicalSortGen{})
	reg.Register("graph.dag_paths", &dagPathsGen{})
	for id, kind := range graphBridgeKinds {
		reg.Register(id, &graphBridgeGen{kind: kind})
	}
	registerWave3(reg)
	registerWave6(reg)
	registerWave6Remaining(reg)
}
