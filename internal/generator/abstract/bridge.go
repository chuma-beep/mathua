type abstractBridgeGen struct{ kind string }

func abstractBridgeOrdinal(ctx generator.GeneratorContext) int {
	if ctx.KPOrdinal >= 1 && ctx.KPOrdinal <= 3 {
		return ctx.KPOrdinal
	}
	return 1 + rand.Intn(3)
}

func abstractBridgeProblem(ordinal int, question, answer, explanation string) generator.Problem {
	return generator.Problem{
		Question:    question,
		Answer:      answer,
		Explanation: explanation,
		KPOrdinal:   ordinal,
		Facts:       map[string]string{"answer": answer},
	}
}

func abstractLCM(a, b int) int { return a / abstractGCD(a, b) * b }

func abstractPhi(n int) int {
	out := n
	m := n
	for p := 2; p*p <= m; p++ {
		if m%p == 0 {
			for m%p == 0 {
				m /= p
			}
			out -= out / p
		}
	}
	if m > 1 {
		out -= out / m
	}
	return out
}

func abstractPartitions(n int) int {
	dp := make([]int, n+1)
	dp[0] = 1
	for k := 1; k <= n; k++ {
		for s := k; s <= n; s++ {
			dp[s] += dp[s-k]
		}
	}
	return dp[n]
}

func abstractMobius(n int) int {
	if n == 1 {
		return 1
	}
	out := 1
	for p := 2; p*p <= n; p++ {
		if n%p == 0 {
			n /= p
			if n%p == 0 {
				return 0
			}
			out = -out
		}
	}
	if n > 1 {
		out = -out
	}
	return out
}

func abstractDivisors(n int) []int {
	var out []int
	for d := 1; d <= n; d++ {
		if n%d == 0 {
			out = append(out, d)
		}
	}
	return out
}

func abstractIrreducibleCount(p, n int) int {
	sum := 0
	for _, d := range abstractDivisors(n) {
		sum += abstractMobius(d) * abstractPow(p, n/d)
	}
	return sum / n
}

