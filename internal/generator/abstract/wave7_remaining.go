func w7Eisenstein(kp int) generator.Problem {
	p := []int{2, 3, 5, 7}[rand.Intn(4)]
	degree := w7RA(3, 4)
	coefs := make([]int, degree+1)
	coefs[degree] = 1
	for i := 0; i < degree; i++ {
		coefs[i] = p * w7RA(1, 3)
	}
	coefs[0] = p * w7RA(1, 3)
	f := map[string]string{"p": strconv.Itoa(p), "degree": strconv.Itoa(degree)}
	f["coefs"] = fmt.Sprintf("%v", coefs)
	switch kp {
	case 1:
		count := 0
		for i := 0; i < degree; i++ {
			if coefs[i]%p == 0 {
				count++
			}
		}
		return w7A(kp, fmt.Sprintf("For the polynomial with coefficients %v and prime \\(p=%d\\), how many non-leading coefficients are divisible by p?", coefs, p), strconv.Itoa(count),
			"Every non-leading coefficient is a positive multiple of p.", f)
	case 2:
		return w7A(kp, fmt.Sprintf("The polynomial with coefficients %v is Eisenstein at \\(p=%d\\). Is it irreducible over Q? Enter 1 for yes and 0 for no.", coefs, p), "1",
			"Eisenstein's criterion gives irreducibility directly.", f)
	default:
		is := 0
		if coefs[0]%(p*p) == 0 {
			is = 1
		}
		w7RAI(f, "p_squared_divides_constant", is)
		return w7A(kp, fmt.Sprintf("For the constant coefficient %d and \\(p=%d\\), does \\(p^2\\) divide the constant? Enter 1 for yes and 0 for no.", coefs[0], p), strconv.Itoa(is),
			fmt.Sprintf("\\(%d^2=%d\\), and the constant is %d.", p, p*p, coefs[0]), f)
	}
}

