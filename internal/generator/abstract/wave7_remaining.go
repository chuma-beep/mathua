type w7AbstractRemainingGen struct{ kind string }

func (g *w7AbstractRemainingGen) Generate(ctx generator.GeneratorContext) generator.Problem {
	kp := ctx.KPOrdinal
	if kp < 1 || kp > 3 {
		kp = 1 + rand.Intn(3)
	}
	switch g.kind {
	case "wreath":
		return w7Wreath(kp)
	case "free_product":
		return w7FreeProduct(kp)
	case "extension":
		return w7Extension(kp)
	case "character":
		return w7Character(kp)
	case "maschke":
		return w7Maschke(kp)
	case "schur":
		return w7Schur(kp)
	case "induced":
		return w7Induced(kp)
	case "resultant":
		return w7Resultant(kp)
	case "discriminant":
		return w7Discriminant(kp)
	case "eisenstein":
		return w7Eisenstein(kp)
	case "fractional_ideal":
		return w7FractionalIdeal(kp)
	case "dedekind":
		return w7Dedekind(kp)
	case "valuation":
		return w7Valuation(kp)
	case "primary":
		return w7Primary(kp)
	case "nakayama":
		return w7Nakayama(kp)
	case "exterior":
		return w7Exterior(kp)
	}
	return generator.Problem{Question: "What is 2 + 2? (enter a number)", Answer: "4", Explanation: "2 + 2 = 4."}
}

func w7RA(lo, hi int) int {
	if hi <= lo {
		return lo
	}
	return lo + rand.Intn(hi-lo+1)
}

func w7RAI(f map[string]string, k string, v int) { f[k] = strconv.Itoa(v) }

func w7Linear(a, b int) string {
	s := fmt.Sprintf("%d x", a)
	if a == 1 {
		s = "x"
	} else if a == -1 {
		s = "-x"
	}
	if b > 0 {
		s += fmt.Sprintf("+%d", b)
	} else if b < 0 {
		s += strconv.Itoa(b)
	}
	return s
}

func w7Quadratic(a, b, c int) string {
	s := fmt.Sprintf("%d x^2", a)
	if a == 1 {
		s = "x^2"
	} else if a == -1 {
		s = "-x^2"
	}
	if b != 0 {
		term := fmt.Sprintf("%d x", b)
		if b == 1 {
			term = "x"
		} else if b == -1 {
			term = "-x"
		}
		if b > 0 {
			s += "+" + term
		} else {
			s += term
		}
	}
	if c > 0 {
		s += fmt.Sprintf("+%d", c)
	} else if c < 0 {
		s += strconv.Itoa(c)
	}
	return s
}

func w7Wreath(kp int) generator.Problem {
	m := w7RA(2, 5)
	n := w7RA(2, 4)
	base := 1
	for i := 0; i < n; i++ {
		base *= m
	}
	f := map[string]string{}
	w7RAI(f, "m", m)
	w7RAI(f, "n", n)
	switch kp {
	case 1:
		return w7A(kp, fmt.Sprintf("For the wreath product \\(C_%d \\wr S_%d\\), what is the order \\(m^n n\\)?", m, n), strconv.Itoa(base*n),
			fmt.Sprintf("\\(|C_%d|^%d\\cdot %d=%d\\).", m, n, n, base*n), f)
	case 2:
		return w7A(kp, fmt.Sprintf("For \\(C_%d \\wr S_%d\\), what is the size of the base group \\(C_%d^%d\\)?", m, n, m, n), strconv.Itoa(base),
			fmt.Sprintf("\\(%d^%d=%d\\).", m, n, base), f)
	default:
		return w7A(kp, fmt.Sprintf("For \\(C_%d \\wr S_%d\\), how many coordinates does the base group act on?", m, n), strconv.Itoa(n),
			"The base group has one copy of the cyclic group for each of the n coordinates.", f)
	}
}

