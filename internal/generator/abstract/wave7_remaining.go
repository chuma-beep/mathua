func w7Dedekind(kp int) generator.Problem {
	n := w7RA(6, 30)
	count := 0
	m := n
	for p := 2; p*p <= m; p++ {
		for m%p == 0 {
			count++
			m /= p
		}
	}
	if m > 1 {
		count++
	}
	f := map[string]string{"n": strconv.Itoa(n)}
	switch kp {
	case 1:
		return w7A(kp, fmt.Sprintf("How many prime factors does %d have, counted with multiplicity?", n), strconv.Itoa(count),
			fmt.Sprintf("Factor %d and count the factors with multiplicity: %d.", n, count), f)
	case 2:
		distinct := 0
		m2 := n
		for q := 2; q <= m2; q++ {
			if m2%q == 0 {
				distinct++
				for m2%q == 0 {
					m2 /= q
				}
			}
		}
		w7RAI(f, "distinct_primes", distinct)
		return w7A(kp, fmt.Sprintf("How many distinct prime ideals appear in the factorization of the ideal generated by %d?", n), strconv.Itoa(distinct),
			"Distinct primes in the factorization of n give distinct prime ideals.", f)
	default:
		return w7A(kp, fmt.Sprintf("If %d has %d prime factors counted with multiplicity, how many does %d squared have?", n, count, n), strconv.Itoa(2*count),
			"Squaring doubles every exponent, so the total count doubles.", f)
	}
}

