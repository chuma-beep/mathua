'use client'

import { useMemo, useState } from 'react'
import FigureFrame from '../FigureFrame'
import { Slider } from '../Controls'
import { groupSchema } from '../schemas'
import { elementOrder, generatedSubgroup, groupById, inverseOf, isAbelian } from '../math/group'
import type { TemplateProps } from '../types'

const W = 360
const H = 300

export default function GroupTable({ params, title, caption }: TemplateProps) {
  const defaults = useMemo(() => groupSchema.parse(params), [params])
  const [groupId, setGroupId] = useState(defaults.group)
  const [element, setElement] = useState(defaults.element)
  const group = groupById(groupId)
  const index = Math.min(element, group.elements.length - 1)
  const order = elementOrder(group, index)
  const inverse = inverseOf(group, index)
  const subgroup = generatedSubgroup(group, index)
  const cell = Math.min(38, 260 / group.elements.length)

  const reset = () => {
    setGroupId(defaults.group)
    setElement(defaults.element)
  }

  return (
    <FigureFrame
      title={title ?? 'The operation table is the group'}
      hint="Pick an element. Its powers, order and inverse come from the table, not from a geometric analogy."
      caption={caption ?? 'A group is a set with an associative operation, an identity and inverses. The table lists every product. A subgroup generated by one element is the set of its powers.'}
      onReset={reset}
      readout={[
        { label: 'group', value: `${group.label} (${group.description})` },
        { label: 'element', value: group.elements[index] },
        { label: 'order', value: String(order) },
        { label: 'inverse', value: group.elements[inverse] },
        { label: 'generated subgroup', value: subgroup.map((i) => group.elements[i]).join(', ') },
        { label: 'abelian', value: isAbelian(group) ? 'yes' : 'no' },
        { label: 'cyclic', value: group.cyclic ? 'yes' : 'no' },
      ]}
    >
      <svg
        viewBox={`0 0 ${W} ${H}`}
        className="mx-auto block h-auto w-full max-w-[420px] font-mono"
        role="img"
        aria-label={`Operation table for ${group.label}`}
      >
        <text x={40} y={18} fontSize="10" fill="var(--text-secondary)">
          {group.label}
        </text>
        {group.elements.map((label, col) => (
          <text key={`h${col}`} x={40 + col * cell + cell / 2} y={38} textAnchor="middle" fontSize="9" fill="var(--text-muted)">
            {label}
          </text>
        ))}
        {group.elements.map((label, row) => (
          <g key={`r${row}`}>
            <text x={34} y={52 + row * cell + cell / 2} textAnchor="end" fontSize="9" fill="var(--text-muted)">
              {label}
            </text>
            {group.elements.map((_col, col) => {
              const value = group.table[row][col]
              const highlight = row === index || col === index
              const inSubgroup = subgroup.includes(value)
              return (
                <g key={`${row}-${col}`}>
                  <rect
                    x={40 + col * cell}
                    y={44 + row * cell}
                    width={cell}
                    height={cell}
                    fill={highlight ? 'var(--accent-blue)' : inSubgroup ? 'var(--chart-2)' : 'transparent'}
                    fillOpacity={highlight ? 0.18 : inSubgroup ? 0.1 : 0}
                    stroke="var(--text-muted)"
                    strokeWidth="0.5"
                  />
                  <text
                    x={40 + col * cell + cell / 2}
                    y={44 + row * cell + cell / 2 + 3}
                    textAnchor="middle"
                    fontSize="9"
                    fill={inSubgroup ? 'var(--accent-blue)' : 'var(--text-secondary)'}
                  >
                    {group.elements[value]}
                  </text>
                </g>
              )
            })}
          </g>
        ))}
        <text x={40} y={44 + group.elements.length * cell + 18} fontSize="10" fill="var(--text-secondary)">
          selected {group.elements[index]}: order {order}, inverse {group.elements[inverse]}
        </text>
      </svg>

      <div className="mt-3 space-y-2">
        <label className="flex items-center justify-between gap-2 font-mono text-[10px] text-mathua-muted">
          <span>Group</span>
          <select
            aria-label="Group"
            value={groupId}
            onChange={(event) => {
              setGroupId(event.target.value as typeof groupId)
              setElement(0)
            }}
            className="h-7 border border-mathua-border bg-transparent px-1 text-[10px] text-mathua-secondary"
          >
            <option value="z4">Z4, addition mod 4</option>
            <option value="z5">Z5, addition mod 5</option>
            <option value="s3">S3, triangle symmetries</option>
          </select>
        </label>
        <div className="grid grid-cols-1 gap-2">
          <Slider
            label="Element"
            value={index}
            min={0}
            max={group.elements.length - 1}
            step={1}
            onChange={setElement}
          />
        </div>
      </div>
    </FigureFrame>
  )
}
